import { afterEach, describe, expect, it } from "vitest";
import { codeFieldSource } from "./code-source";
import { targetCheck, targetState } from "./target-state";

// Runs in Chromium (vitest browser mode) so layout and computed styles decide what shows.
afterEach(() => {
  document.head.querySelector("#luma-style")?.remove();
  document.body.innerHTML = "";
});

const code = { by: "autocomplete", value: "one-time-code" } as const;
const field = () => document.querySelector<HTMLInputElement>("input[autocomplete]")!;

// Luma's sign-in dialog, captured from luma.com on 2026-11-17 (#1655): the emailed code's
// page and then, on the same path and in the same document, the authenticator app's
// code page. Both inputs are alike, one input at opacity 0 over six `aria-hidden` boxes
// with React `useId` ids. The site's stylesheet is reduced to the rules that lay them out.
const lumaStyle = `.container { position: relative; display: flex; gap: 8px; width: 320px; height: 44px }
  .slot { width: 40px; height: 44px; border: 1px solid }
  .input { position: absolute; inset: 0; opacity: 0 }`;
const boxes = `<div aria-hidden="true" class="jsx-f9dccacfdd7efe10 slot animated rounded active"><div class="jsx-f9dccacfdd7efe10 caret"></div></div>${'<div aria-hidden="true" class="jsx-f9dccacfdd7efe10 slot animated rounded"></div>'.repeat(5)}`;
const back = `<div class="pb-4" style="opacity: 1; top: 0px; transform: none;"><button aria-label="Back" class="lux-menu-trigger-wrapper btn lux-button flex-center small light solid variant-color-light round icon-only-compact" type="button"><svg></svg></button></div>`;
const paste = `<button class="btn lux-button flex-center small light solid variant-color-light icon-left" type="button"><svg></svg><div class="label">Paste Code</div></button>`;
const card = (inner: string) =>
  `<div class="onboarding-card overflow-hidden show-border" style="opacity: 1;"><div class="relative" style="height: 234px;"><div class="animated-container" style="position: absolute; top: 0px; width: 100%;">${back}<div style="opacity: 1; top: 0px; transform: none;">${inner}</div></div></div></div>`;
const emailCode = card(
  `<div class="jsx-1620022762 mb-3"><h3 class="jsx-1620022762 title">Enter Code</h3><div id="_r_4_" class="jsx-1620022762 text-secondary-alpha fs-sm"><span>Please enter the 6 digit code we sent to <span class="text-primary">nobody@example.com</span>.</span></div></div><div><div class="jsx-f9dccacfdd7efe10 "><div class="jsx-f9dccacfdd7efe10 container spread">${boxes}<input id="_r_8_" inputmode="numeric" pattern="[0-9]*" autocomplete="one-time-code" data-1p-ignore="true" data-lpignore="true" data-bwignore="true" data-form-type="other" aria-label="Verification code" aria-describedby="_r_4_" class="jsx-f9dccacfdd7efe10 input" type="text" value=""></div></div><div class="flex-center pt-3 mt-1 spread flex-wrap gap-2">${paste}<div class="text-tertiary-alpha fs-sm mono-number">Resend code in 58s</div></div></div>`,
);
const authenticatorCode = `<div class="jsx-4153170419 onboarding-page">${card(
  `<div class="jsx-1620022762 mb-3"><h3 class="jsx-1620022762 title">Two-Factor Authentication</h3><div class="jsx-1620022762 text-secondary-alpha fs-sm">Please enter the code generated by your authenticator app.</div></div><div class="jsx-f9dccacfdd7efe10 "><div class="jsx-f9dccacfdd7efe10 container spread">${boxes}<input id="_r_c_" inputmode="numeric" pattern="[0-9]*" autocomplete="one-time-code" aria-label="Verification code" class="jsx-f9dccacfdd7efe10 input" type="text" value=""></div></div><div class="mt-1 pt-3">${paste}</div>`,
)}</div>`;
const luma = (html: string) => {
  document.head.insertAdjacentHTML("beforeend", `<style id="luma-style">${lumaStyle}</style>`);
  document.body.innerHTML = html;
};

describe("a totp handler's code field (ADR 0027 amendment of 2026-11-17)", () => {
  it("takes Luma's authenticator app's code page", () => {
    luma(authenticatorCode);
    expect(codeFieldSource(field())).toBe("authenticator");
    expect(targetState(document, code, "totp-code")).toBe("unique");
    expect(targetCheck(document, code, "totp-code")).toBe("ok");
  });

  it("refuses Luma's emailed code's page on the same path, though its input is alike", () => {
    luma(emailCode);
    expect(codeFieldSource(field())).toBe("sent");
    // The same input passes every check but the page's words.
    expect(targetState(document, code, "writable")).toBe("unique");
    expect(targetState(document, code, "totp-code")).toBe("unusable");
    expect(targetCheck(document, code, "totp-code")).toBe("code-sent");
  });

  it("reads the field's description, though nothing near it says so", () => {
    document.body.innerHTML = `<p id="hint" style="position:absolute;top:400px">We emailed you a code.</p>
      <div><div><div><div><div><div><div><input autocomplete="one-time-code" aria-describedby="hint"></div></div></div></div></div></div></div>`;
    expect(codeFieldSource(field())).toBe("sent");
    expect(targetCheck(document, code, "totp-code")).toBe("code-sent");
  });

  it("reads the heading of the open modal dialog that holds the field", () => {
    document.body.innerHTML = `<h1>Account security</h1>
      <div role="dialog" aria-modal="true"><h2>Check your email</h2>
        <div><div><div><div><div><div><div><input autocomplete="one-time-code" aria-label="Code"></div></div></div></div></div></div></div>
      </div>`;
    expect(codeFieldSource(field())).toBe("sent");
    expect(targetState(document, code, "totp-code")).toBe("unusable");
  });

  it("takes a page that says nothing about where its code comes from", () => {
    document.body.innerHTML = `<h1>Two-step verification</h1><form><p>Enter the verification code</p>
      <input autocomplete="one-time-code" aria-label="Code"><button>Verify</button></form>`;
    expect(codeFieldSource(field())).toBeUndefined();
    expect(targetState(document, code, "totp-code")).toBe("unique");
  });

  it("leaves out the words of another form's part of the page", () => {
    // A newsletter form beside the code holds its own field: its heading and text are not
    // the code's.
    document.body.innerHTML = `<main><section><h2>Get our news by email</h2>
        <p>We send it every week.</p><input type="email" aria-label="Email"></section>
      <div><p>Enter the code</p><input autocomplete="one-time-code" aria-label="Code"></div></main>`;
    expect(codeFieldSource(field())).toBeUndefined();
    expect(targetState(document, code, "totp-code")).toBe("unique");
  });

  it("still names a field it cannot write by why", () => {
    luma(emailCode);
    field().disabled = true;
    expect(targetCheck(document, code, "totp-code")).toBe("not-writable");
  });
});
