import { isCodeField, judgedCodeInput, type LoginObservation } from "./observation";

/**
 * Words, per language, of a button that goes on to typing a code from an authenticator
 * app on a page that asks how to confirm the sign-in (ADR 0081): English `authenticator`
 * with `app` or `code` beside it somewhere in the text, `authentication app`, `auth app`
 * and `TOTP` as whole words, and Japanese 認証アプリ and 認証システム (as in 「Google 認証
 * システム」). A bare "Authenticator", as "Sign in with Authenticator", more often starts
 * a push approval. Matched case-insensitively. A language is added here, never a site.
 */
const authenticatorWords =
  /\b(?:authentication\s*apps?|auth\s*apps?|totp)\b|認証アプリ|認証システム/iu;
const bareAuthenticator = /\bauthenticators?\b/iu;
const appOrCode = /\b(?:apps?|codes?)\b/iu;
/**
 * Words that make such a text another way or another task: a code sent by SMS, a text
 * message, a call or email, or sent at all; a backup or recovery code; an approval or
 * push notification or number matching; a passkey, security key, FIDO, U2F, WebAuthn,
 * built-in, platform or roaming authenticator or the device's biometrics; setting up, adding, registering, enabling, changing, resetting or removing an
 * authenticator; a lost one, help, another or a different way, cancelling, and signing or
 * logging out. Latin words match whole words; Japanese ones anywhere. "Code", "app",
 * "phone" and "mobile" stay neutral: "Use code from the authenticator app on your phone"
 * names the choice.
 */
const otherWords =
  /\b(?:sms|texts?|texting|message|messages|call|calls|calling|voice|e\s*mail|email|emails|mail|send|sent|resend|backup|back\s*up|recovery|recover|scratch|push|notifications?|approve|approval|request|prompt|passkeys?|security\s*keys?|hardware|built\s*in|platform|roaming|fido\w*|u2f|webauthn|yubikey|number\s*match\w*|touch\s*id|face\s*id|fingerprints?|biometrics?|windows\s*hello|set\s*up|setup|add|register|enroll|enable|disable|new|change|update|reset|remove|delete|lost|forgot|without|another|other|different|help|trouble|problem|cancel|link|magic|(?:sign|log)\s*(?:out|off))\b|ショートメッセージ|メッセージ|電話|通話|音声|メール|送信|送る|再送|バックアップ|リカバリ|復旧|予備|回復|プッシュ|通知|承認|パスキー|セキュリティキー|生体|指紋|顔|設定|登録|追加|有効|無効|変更|再設定|解除|削除|忘れ|紛失|お困り|わから|できない|別|他|キャンセル|ログアウト|サインアウト/iu;

const words = (text: string) => text.replaceAll(/[^\p{L}\p{N}]+/gu, " ");

/**
 * Whether a button's text names a code from an authenticator app as the way to confirm
 * the sign-in, such as "Authenticator app", "Use code from authenticator" or
 * 「認証アプリを使用」, and nothing else: "Text me a code", "Use backup code", "Set up an
 * authenticator app", "Use a security key" and 「別の方法を試す」 do not (ADR 0081).
 * Shared by the service, which checks the judged page's button, and the extension, which
 * checks the live button before pressing.
 */
export function namesAuthenticatorChoice(text: string): boolean {
  const spaced = words(text);
  return (
    (authenticatorWords.test(spaced) ||
      (bareAuthenticator.test(spaced) && appOrCode.test(spaced))) &&
    !otherWords.test(spaced)
  );
}

/**
 * Whether a text holds one of the words that make a button another way than the
 * authenticator app's code, the ones {@link namesAuthenticatorChoice} refuses.
 */
export function namesOtherThanAuthenticator(text: string): boolean {
  return otherWords.test(words(text));
}

/**
 * Where the code a code field takes comes from, as the words its page shows around it say
 * ({@link codeSourceOf}): an authenticator app, or a code the site sent to the person.
 */
export type CodeSource = "authenticator" | "sent";

/**
 * Words, per language, that name an authenticator app as where a code comes from: those
 * of {@link namesAuthenticatorChoice} (`authentication app`, `auth app`, `TOTP`, 認証アプリ,
 * 認証システム) and 認証用アプリ, and `authenticator` with `app`, `code`, アプリ or コード
 * beside it in the same text, or right after one of `generated`, `created`, `shown`,
 * `displayed` or `from`, then optionally one of `by`, `in` or `on`, then optionally one of
 * `your`, `the`, `a` or `an`, as "generated by your authenticator" and "from the
 * authenticator" are; and `app authentication` or `app-based authentication`, as
 * ImmiAccount's heading "App authentication" over its code field is (ADR 0027 amendment
 * of 2026-11-22). A bare "Authenticator", as a push approval's "Check Microsoft
 * Authenticator", names no code. Matched case-insensitively. A language is added here,
 * never a site.
 */
const authenticatorSource = /\bapps?\s+(?:based\s+)?authentication\b|認証用アプリ/iu;
const authenticatorAfter =
  /\b(?:generated|created|shown|displayed|from)\s+(?:(?:by|in|on)\s+)?(?:your\s+|the\s+|an?\s+)?authenticators?\b/iu;
const appOrCodeAnywhere = /\b(?:apps?|codes?)\b|アプリ|コード/iu;
/**
 * Words, per language, that say a code was sent or delivered to the person, as a verb
 * does, never a noun or a button's name alone (ADR 0027 amendment of 2026-11-17):
 *
 * - English, as whole words (no letter or digit of any script beside them, so "sentí"
 *   is none): `sent`, `resent`, `delivered`, `emailed`, `e-mailed`, `mailed`, `texted`
 *   and `text message`; and `send`, `sending` or `resend` followed, past at most three
 *   of `a`, `an`, `the`, `new`, `another`, `me`, `you`, `us`, `it`, `your`, `one` or
 *   `this`, by `code`, `again`, `in`, `link`, `email`, `e-mail`, `SMS`, `text`,
 *   `message`, `verification`, `OTP`, `PIN` or `one-time`, as "Resend code in 58s" and
 *   "We'll send you a code" are. A bare "Send" or "Resend", as a button or the email
 *   service "Resend" ("Log in to Resend"), says nothing.
 * - Japanese, anywhere: 送信, 送付 followed by しま, した, され, させ, される or 済
 *   (送信しました, 送信された, 送信済み), 送り, 送ら or 送っ unless after 見 (お送り
 *   しました, 送られた, 見送り excluded), 再送, 届い, 届き, 届く and ショートメッセージ.
 *   A bare 送信, as a 「送信」 button, and the request 「送信してください」 say nothing.
 *
 * "Email", "e-mail", "mail", "inbox", "SMS", メール, "phone", "mobile", "device", "code",
 * "app", "message" and a bare "text" stay neutral, as a page's label for the account's
 * address (「ログイン中のメールアドレス」) or a link to another way is no sent code, as
 * they do for {@link namesAuthenticatorChoice}. An email address, and the observation's
 * `[email]`, `[masked]` and `[number]` that stand for a redacted one, a masked value or a
 * number, are read as no word. Matched case-insensitively, after width folding. A
 * language is added here, never a site.
 */
const sentWords =
  /(?<![\p{L}\p{N}])(?:sent|resent|delivered|e\s*mailed|mailed|texted|text\s+messages?|(?:re)?send(?:ing)?\s+(?:(?:a|an|the|new|another|me|you|us|it|your|one|this)\s+){0,3}(?:codes?|again|in|links?|e\s*mails?|sms|text|messages?|verification|otp|pin|one\s*time))(?![\p{L}\p{N}])|(?:送信|送付)(?:しま|した|され|さ[せれ]|済)|(?<!見)送[りらっ]|再送|届[いきく]|ショートメッセージ/iu;

/**
 * Where the code a code field takes comes from, as the texts its page shows around the
 * field say (ADR 0027 amendment of 2026-11-17): `authenticator` when one of them names an
 * authenticator app ("Please enter the code generated by your authenticator app.",
 * 「認証アプリに表示されたコードを入力」) and none says a code was sent, `sent` when one
 * says the code was sent or delivered ("Please enter the 6 digit code we sent to …",
 * "Resend code in 58s", 「メールに届いた確認コード」) and none names an authenticator app,
 * and `undefined` when the texts say neither, as "Enter the verification code" does, or
 * both. Shared by the service and the extension; it reads words only, never a site.
 */
export function codeSourceOf(texts: readonly string[]): CodeSource | undefined {
  let authenticator = false;
  let sent = false;
  for (const text of texts) {
    // Each whitespace-separated piece holding an `@` is an address; split first, so the
    // match never scans the rest of the text again from each character.
    const folded = text
      .normalize("NFKC")
      .replaceAll(/\[(?:email|masked|number)\]/gu, " ")
      .split(/\s+/u)
      .filter((piece) => !piece.includes("@"))
      .join(" ");
    const spaced = words(folded);
    if (
      authenticatorWords.test(spaced) ||
      authenticatorSource.test(spaced) ||
      authenticatorAfter.test(spaced) ||
      (bareAuthenticator.test(spaced) && appOrCodeAnywhere.test(spaced))
    )
      authenticator = true;
    if (sentWords.test(spaced)) sent = true;
  }
  return authenticator === sent ? undefined : authenticator ? "authenticator" : "sent";
}

/**
 * Where the code of a described page's first code field comes from (`codeSourceOf`, ADR
 * 0029 amendment of 2026-11-17), as the page's title and headings, the texts near the field
 * and the field's own label, placeholder and description say: Luma's "Enter Code" page says
 * its code was sent, and its "Two-Factor Authentication" page on the same path names an
 * authenticator app. A page without a code field that `isCodeField` takes reads its only
 * input that the judge may name a code field (`judgedCodeInput`), as ImmiAccount's
 * `#authenticationCode` (ADR 0027 amendment of 2026-11-22), without near texts, which the
 * description carries only beside an `isCodeField` input; with none, or several, it has
 * no code field. Empty on a page without a code field, or whose texts say neither or both.
 * The service keys a page's kept judgement by it; the extension sends a watched code page to
 * the judge only when it is `authenticator`, and a watched login takes over the `totp`
 * handler the judge learns on such a page (ADR 0027 amendments of 2026-11-17 and
 * 2026-11-22).
 */
export function judgedCodeSource(observation: LoginObservation): CodeSource | "" {
  const judged = observation.candidates.filter(judgedCodeInput);
  const code =
    observation.candidates.find(isCodeField) ?? (judged.length === 1 ? judged[0] : undefined);
  if (!code) return "";
  return (
    codeSourceOf([
      observation.title ?? "",
      ...(observation.headings ?? []),
      ...(observation.nearCode ?? []),
      code.label ?? "",
      code.placeholder ?? "",
      code.description ?? "",
    ]) ?? ""
  );
}
