import { describe, expect, it } from "vitest";
import {
  codeSourceOf,
  namesAuthenticatorChoice,
  namesOtherThanAuthenticator,
} from "./authenticator-choice";

describe("a button that goes on to an authenticator app's code (ADR 0081)", () => {
  it.each([
    "Authenticator app",
    "AUTHENTICATOR APP",
    "Use code from authenticator",
    "Authenticator app Use code from authenticator",
    "Use your authenticator app",
    "Use a verification code from Microsoft Authenticator",
    "Use an authentication app",
    "Enter a code from your auth app",
    "TOTP",
    "Use code from the authenticator app on your phone",
    "認証アプリ",
    "認証アプリを使用",
    "認証アプリのコードを入力",
    "Google 認証システム アプリから確認コードを取得する",
  ])("names the authenticator choice in %s", (text) => {
    expect(namesAuthenticatorChoice(text)).toBe(true);
  });

  it.each([
    "Text me a code",
    "Send a code by SMS",
    "Call me",
    "Email me a code",
    "Use backup code",
    "Use a recovery code",
    "Approve a request on my authenticator app",
    "Send a push notification to the authenticator",
    "Use a passkey",
    "Use a security key or authenticator",
    "Use a FIDO2 authenticator",
    "WebAuthn authenticator",
    "Use a roaming authenticator",
    "Microsoft Authenticator",
    "Sign in with Authenticator",
    "Number matching in Authenticator app",
    "Use Windows Hello",
    "Set up an authenticator app",
    "Add an authenticator",
    "Lost your authenticator?",
    "Try another way",
    "Use a different method",
    "Cancel",
    "Log out",
    "Password",
    "Use code",
    "認証アプリを設定",
    "SMS で認証",
    "別の方法を試す",
    "その他の方法",
    "バックアップコードを使用",
    "パスキー",
  ])("does not name it in %s", (text) => {
    expect(namesAuthenticatorChoice(text)).toBe(false);
  });

  it("tells another way's words apart from neutral ones", () => {
    expect(namesOtherThanAuthenticator("Text me a code")).toBe(true);
    expect(namesOtherThanAuthenticator("Select")).toBe(false);
    expect(namesOtherThanAuthenticator("Use code from your app")).toBe(false);
  });
});

describe("where a code comes from, by the words around its field (ADR 0027 amendment of 2026-11-17)", () => {
  it.each([
    // Luma's second code page, in the same dialog and on the same path as its email code.
    [["Two-Factor Authentication", "Please enter the code generated by your authenticator app."]],
    [
      [
        "Two-factor authentication",
        "Open your two-factor authenticator (TOTP) app or browser extension to view your authentication code.",
      ],
    ],
    [["2-Step Verification", "Get a verification code from the Google Authenticator app"]],
    [
      [
        "nobody@example.com",
        "Enter code",
        "Enter the code displayed in the Microsoft Authenticator app on your mobile device",
      ],
    ],
    [["Enter the MFA code from your authentication app"]],
    [["Enter the number generated by your authenticator"]],
    [["Use the 6-digit code from your auth app"]],
    [["TOTP"]],
    [["二段階認証", "認証アプリに表示されている6桁のコードを入力してください"]],
    [["Google 認証システムで生成された確認コードを入力"]],
    [["認証用アプリのワンタイムパスワードを入力"]],
    [["Google Authenticatorアプリのコードを入力してください"]],
    // The account's address, raw or as the observation redacts it, is no word.
    [["[email]", "Enter the code from your authenticator app"]],
    [["[email]でログイン中", "認証アプリのコードを入力"]],
  ])("reads %j as an authenticator app's code", (texts) => {
    expect(codeSourceOf(texts)).toBe("authenticator");
  });

  it.each([
    // Luma's first code page: its heading, the description the input names, and its timer.
    [
      [
        "Enter Code",
        "Please enter the 6 digit code we sent to nobody@example.com.",
        "Resend code in 58s",
      ],
    ],
    [
      [
        "Device verification",
        "We just sent your authentication code via email to n***@example.com.",
      ],
    ],
    [["We just sent you a message via SMS with your authentication code."]],
    [["A text message with a 6-digit verification code was just sent to •••-•••-••12"]],
    [["Check your inbox for a sign-in code"]],
    [["We texted a code to your phone"]],
    [["Enter the code we e-mailed you"]],
    [["Didn't get it? Resend"]],
    [["ご登録のメールアドレスに認証コードを送信しました。"]],
    [["SMSで届いた確認コードを入力してください"]],
    [["ＳＭＳに届いたコード"]],
    [["ショートメッセージに記載の認証コードを入力"]],
    [["確認コードをお送りしました"]],
    [["Please enter the [number] digit code we sent to [email]."]],
  ])("reads %j as a code sent to the person", (texts) => {
    expect(codeSourceOf(texts)).toBe("sent");
  });

  it.each([
    [[]],
    [["Enter the verification code"]],
    [["Two-factor authentication", "Verification code"]],
    [["Enter the code from the app on your phone"]],
    [["Check Microsoft Authenticator"]],
    [["Check your messages"]],
    [["Enter the text shown"]],
    [["Signed in as nobody@mail.example.com", "Enter code"]],
    [["確認コードを入力してください"]],
    // Both: the page names the app and says it can send a code too.
    [["Enter the code from your authenticator app", "Or we can send a code by SMS"]],
    [["認証アプリまたはメールに届いたコードを入力"]],
  ])("reads %j as saying neither, or both", (texts) => {
    expect(codeSourceOf(texts)).toBeUndefined();
  });
});
